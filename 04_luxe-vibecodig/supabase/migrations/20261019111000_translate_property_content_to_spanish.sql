UPDATE public.properties AS property
SET
  description_es = translations.description_es,
  amenities_es = CASE
    WHEN property.amenities IS NULL THEN NULL
    ELSE ARRAY(
      SELECT CASE amenity
        WHEN 'Air Conditioning' THEN 'Aire acondicionado'
        WHEN 'Backyard' THEN 'Patio trasero'
        WHEN 'Bike Storage' THEN 'Bicicletero'
        WHEN 'Central Heating & Cooling' THEN 'Calefacción y aire acondicionado central'
        WHEN 'Concierge' THEN 'Conserjería'
        WHEN 'Concierge Service' THEN 'Servicio de conserjería'
        WHEN 'Doorman' THEN 'Portero'
        WHEN 'Electric Vehicle Charging' THEN 'Estación de carga para vehículos eléctricos'
        WHEN 'Exposed Brick' THEN 'Ladrillo expuesto'
        WHEN 'Fireplace' THEN 'Chimenea'
        WHEN 'Fitness Center' THEN 'Gimnasio'
        WHEN 'Garage' THEN 'Garaje'
        WHEN 'Gym' THEN 'Gimnasio'
        WHEN 'Hardwood Floors' THEN 'Pisos de madera'
        WHEN 'Heated Floors' THEN 'Pisos radiantes'
        WHEN 'High-speed Wifi' THEN 'Wifi de alta velocidad'
        WHEN 'Home Cinema' THEN 'Cine en casa'
        WHEN 'Home Office' THEN 'Oficina en casa'
        WHEN 'Infinity Pool' THEN 'Piscina infinita'
        WHEN 'Mountain Views' THEN 'Vistas a la montaña'
        WHEN 'Ocean Views' THEN 'Vistas al océano'
        WHEN 'Parking' THEN 'Estacionamiento'
        WHEN 'Patio / Terrace' THEN 'Patio / Terraza'
        WHEN 'Pet Friendly' THEN 'Se permiten mascotas'
        WHEN 'Polished Concrete' THEN 'Concreto pulido'
        WHEN 'Pool' THEN 'Piscina'
        WHEN 'Private Beach Access' THEN 'Acceso privado a la playa'
        WHEN 'Private Elevator' THEN 'Ascensor privado'
        WHEN 'Private Forest' THEN 'Bosque privado'
        WHEN 'Private Gym' THEN 'Gimnasio privado'
        WHEN 'Private Lake Access' THEN 'Acceso privado al lago'
        WHEN 'Renovated Kitchen' THEN 'Cocina renovada'
        WHEN 'Rooftop Access' THEN 'Acceso a la azotea'
        WHEN 'Rooftop Terrace' THEN 'Terraza en la azotea'
        WHEN 'Smart Home System' THEN 'Sistema de hogar inteligente'
        WHEN 'Spa' THEN 'Spa'
        WHEN 'Storage' THEN 'Espacio de almacenamiento'
        WHEN 'Swimming Pool' THEN 'Piscina'
        WHEN 'Valet Parking' THEN 'Estacionamiento con valet'
        WHEN 'Wine Cellar' THEN 'Cava de vinos'
        WHEN 'Wraparound Terrace' THEN 'Terraza envolvente'
        ELSE amenity
      END
      FROM unnest(property.amenities) WITH ORDINALITY AS amenities(amenity, position)
      ORDER BY position
    )
  END
FROM translations
WHERE property.id = translations.id;
