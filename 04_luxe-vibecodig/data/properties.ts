export function formatPrice(price: number, pricePeriod?: 'mo' | 'year'): string {
  const formatted = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(price);

  if (pricePeriod === 'mo') {
    return `${formatted}`;
  }
  return formatted;
}
